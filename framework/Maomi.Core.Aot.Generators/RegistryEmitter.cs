using System.Text;
using Microsoft.CodeAnalysis;

namespace Maomi.Core.Aot.Generators;

/// <summary>
/// 注册表代码发射器：生成 MaomiAotGeneratedRegistry 代码.
/// </summary>
internal static class RegistryEmitter
{
    public static string Emit(
        List<ModuleModel> modules,
        List<(string MethodName, List<ServiceModel> Services)> chunks,
        Dictionary<string, string> chunkMethodNamesByAssemblyName)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated by Maomi.Core.Aot.Generators />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine();
        builder.AppendLine("namespace Maomi");
        builder.AppendLine("{");
        builder.AppendLine("    internal static class MaomiAotGeneratedRegistry");
        builder.AppendLine("    {");
        builder.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        builder.AppendLine("        internal static void MaomiAotInitialize()");
        builder.AppendLine("        {");

        foreach (var module in modules)
        {
            EmitModuleRegistration(builder, module, chunkMethodNamesByAssemblyName);
        }

        builder.AppendLine("        }");
        builder.AppendLine();

        foreach (var chunk in chunks)
        {
            EmitChunkMethod(builder, chunk.MethodName, chunk.Services);
        }

        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static void EmitModuleRegistration(StringBuilder builder, ModuleModel module, Dictionary<string, string> chunkMethodNamesByAssemblyName)
    {
        builder.Append("            MaomiAotRegistry.RegisterModule(typeof(");
        builder.Append(module.TypeName);
        builder.Append("), ");

        // 依赖列表
        if (module.Dependencies.IsEmpty)
        {
            builder.Append("global::System.Array.Empty<global::System.Type>()");
        }
        else
        {
            builder.Append("new global::System.Type[] { ");
            var first = true;
            foreach (var dependency in module.Dependencies)
            {
                if (!first)
                {
                    builder.Append(", ");
                }

                builder.Append("typeof(");
                // 依赖名是元数据名（嵌套类型用 + 连接），typeof 需要 C# 语法的点号形式
                builder.Append(dependency.Replace('+', '.'));
                builder.Append(")");
                first = false;
            }

            builder.Append(" }");
        }

        // 模块工厂
        builder.Append(", ");
        if (module.Factory.HasFactory)
        {
            builder.Append("static sp => (object)");
            builder.Append(module.Factory.FactoryBody);
        }
        else
        {
            builder.Append("null");
        }

        // 程序集注册块
        builder.Append(", ");
        if (chunkMethodNamesByAssemblyName.TryGetValue(module.AssemblyName, out var chunkMethodName))
        {
            builder.Append(chunkMethodName);
        }
        else
        {
            builder.Append("null");
        }

        builder.AppendLine(");");
    }

    private static void EmitChunkMethod(StringBuilder builder, string methodName, List<ServiceModel> services)
    {
        builder.Append("        private static void ");
        builder.Append(methodName);
        builder.AppendLine("(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        builder.AppendLine("        {");

        foreach (var service in services)
        {
            EmitServiceRegistrations(builder, service);
        }

        builder.AppendLine("        }");
        builder.AppendLine();
    }

    private static void EmitServiceRegistrations(StringBuilder builder, ServiceModel service)
    {
        var lifetimeName = service.Lifetime switch
        {
            MaomiLifetime.Transient => "Transient",
            MaomiLifetime.Singleton => "Singleton",
            _ => "Scoped"
        };

        foreach (var registration in service.Registrations)
        {
            builder.Append("            services.Add");
            if (service.ServiceKeyLiteral != null)
            {
                builder.Append("Keyed");
            }

            builder.Append(lifetimeName);
            builder.Append("(typeof(");
            builder.Append(registration);
            builder.Append("), ");

            if (service.ServiceKeyLiteral != null)
            {
                builder.Append(service.ServiceKeyLiteral);
                builder.Append(", ");
            }

            if (service.Factory.HasFactory)
            {
                // 键控服务的工厂重载是 Func<IServiceProvider, object, object>（第二个参数为 serviceKey）
                builder.Append(service.ServiceKeyLiteral != null ? "static (sp, serviceKey) => " : "static sp => ");
                builder.Append(service.Factory.FactoryBody);
            }
            else
            {
                builder.Append("typeof(");
                builder.Append(service.TypeName);
                builder.Append(")");
            }

            builder.AppendLine(");");
        }
    }
}
